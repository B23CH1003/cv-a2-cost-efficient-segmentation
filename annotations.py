def render(names=None):
    out = os.path.join(common.ROOT, "captured", "masks_256")
    os.makedirs(out, exist_ok=True)
    for name, polys in POLYS.items():
        if names and name not in names:
            continue
        m = np.zeros((common.SIZE, common.SIZE), np.uint8)
        for p in polys:
            cv2.fillPoly(m, [np.array(p, np.int32)], 255)
        for pts, thick in STROKES.get(name, []):
            cv2.polylines(m, [np.array(pts, np.int32)], False, 255, thickness=thick)
        cv2.imwrite(os.path.join(out, name + ".png"), m)


if __name__ == "__main__":
    render()
