def ellipse(cx, cy, ax, ay, n=24):
    """Polygon approximating an axis-aligned ellipse (bicycle wheels seen at an angle)."""
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    return [(round(cx + ax * np.cos(a), 1), round(cy + ay * np.sin(a), 1)) for a in t]


